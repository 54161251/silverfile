"""P6: rebuild the sanitized execution traces for the two evaluation cases.

    python traces/make_traces.py

Runs eval_case_1 (clean) and eval_case_2 (E6, resolved by staff) through the real agents in a
throwaway database under runtime/, walks every LangGraph checkpoint in order, and writes
traces/eval_case_1.json and traces/eval_case_2.json.

Sanitized: SSNs, names and account details go through src.security.pii.mask_data, raw intake
answers and document boxes are left out (only counts and box keys), and the script refuses to
write a file that still contains an unmasked SSN. Timestamps differ on every run.
"""
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.chdir(ROOT)

from run import production_adapters  # noqa: E402
from src.memory import open_sessions  # noqa: E402
from src.security.pii import contains_raw_ssn, mask_data  # noqa: E402

DB = Path(os.getenv("SILVERFILE_TRACE_DB", ROOT / "runtime" / "traces.sqlite"))
OUT = ROOT / "traces"
CASES = [
    ("eval_case_1", "demo/eval_case_1_input.json", None),
    ("eval_case_2", "demo/eval_case_2_input.json", "demo/eval_case_2_resolution.json"),
]


def escalation_view(record):
    keep = ("id", "code", "kind", "raised_by", "reason", "status", "created_at")
    view = {key: record.get(key) for key in keep}
    resolution = record.get("resolution") or {}
    if resolution:
        view["resolution"] = {key: resolution.get(key) for key in ("option", "resolved_by", "resolved_at", "note")}
    return view


def step_view(snapshot):
    values = snapshot.values
    return {
        "step": snapshot.metadata.get("step"),
        "last_agent": values.get("last_agent"),
        "next": list(snapshot.next),
        "status": values.get("status"),
        "documents": len(values.get("documents") or []),
        "open_questions": len(values.get("open_questions") or []),
        "open_escalations": [e["id"] for e in values.get("escalations") or [] if e.get("status") == "open"],
        "lines": len(values.get("lines") or {}),
        "review_verdict": values.get("review_verdict"),
        "iterations": values.get("iterations"),
    }


def final_view(values):
    lines = values.get("lines") or {}
    return {
        "status": values.get("status"),
        "filing_status": values.get("filing_status_validated"),
        "box_count_12d": values.get("box_count_12d"),
        "scope_in_scope": (values.get("scope") or {}).get("in_scope"),
        "documents": [{"doc_id": d.get("doc_id"), "form": d.get("form"), "boxes_read": sorted(d.get("boxes") or {}),
                       "unverified": d.get("unverified")} for d in values.get("documents") or []],
        "escalations": [escalation_view(e) for e in values.get("escalations") or []],
        "review_verdict": values.get("review_verdict"),
        "review_findings": values.get("review_findings"),
        "handoffs": values.get("handoff_history"),
        "total_handoffs": values.get("total_handoffs"),
        "lines": {key: {"value": rec.get("value"), "kind": rec.get("kind"),
                        "tool": (rec.get("tool") or {}).get("name"), "formula": rec.get("formula")}
                  for key, rec in lines.items()},
    }


def trace(sessions, name, input_path, resolution_path):
    thread = f"trace-{name}"
    sessions.start(thread, json.loads(Path(input_path).read_text(encoding="utf-8")))
    events = [{"event": "start", "input": input_path}]
    if resolution_path:
        paused = sessions.snapshot(thread).values
        events.append({"event": "paused_for_staff", "pending_escalation": paused.get("pending_escalation")})
        sessions.resume(thread, json.loads(Path(resolution_path).read_text(encoding="utf-8")))
        events.append({"event": "staff_resolution", "input": resolution_path})
    history = list(sessions.graph.get_state_history(sessions.config(thread)))[::-1]
    record = {
        "case": name,
        "note": "Synthetic data. Generated by traces/make_traces.py; personal details masked.",
        "events": events,
        "steps": [step_view(c) for c in history if c.values],
        "final": final_view(history[-1].values),
    }
    record = mask_data(record)
    text = json.dumps(record, indent=2, default=str)
    if contains_raw_ssn(text):
        raise SystemExit(f"{name}: unmasked SSN found, trace not written")
    (OUT / f"{name}.json").write_text(text + "\n", encoding="utf-8")
    final = record["final"]
    print(f"{name}: {final['status']}, {len(record['steps'])} checkpoints, "
          f"refund {final['lines'].get('34', {}).get('value')}, owed {final['lines'].get('37', {}).get('value')}")


def main():
    DB.parent.mkdir(exist_ok=True)
    if DB.exists():
        DB.unlink()
    with open_sessions(DB, production_adapters()) as sessions:
        for name, input_path, resolution_path in CASES:
            trace(sessions, name, input_path, resolution_path)


if __name__ == "__main__":
    main()
